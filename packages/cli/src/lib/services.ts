import { existsSync } from 'node:fs';
import { join } from 'node:path';

export type AppService = 'api' | 'worker' | 'renderer' | 'admin';
export const APP_SERVICES: AppService[] = ['api', 'worker', 'renderer', 'admin'];

export interface ServiceCommand {
  cmd: string;
  args: string[];
  cwd?: string;
  /** Extra env (ports). */
  env?: Record<string, string>;
}

export interface ServiceSpec {
  name: AppService;
  pkg: string;
  dir: string;
  portKey?: 'API_PORT' | 'RENDERER_PORT' | 'ADMIN_PORT';
  defaultPort?: number;
  /** HTTP path that answers when the service is up. */
  healthPath?: string;
  dev(ports: Record<string, number>): ServiceCommand;
  prod(ports: Record<string, number>, root: string): ServiceCommand;
  /** Build output that must exist for `start --prod`. */
  buildOutput: string;
  procfile: { dev: string; prod: string };
}

const next = (dir: string, mode: 'dev' | 'start', port: number): ServiceCommand => ({ cmd: 'pnpm', args: ['--dir', dir, 'exec', 'next', mode, '--port', String(port)] });

