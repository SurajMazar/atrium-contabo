export function parseOnly(only: string | undefined): AppService[] {
  if (!only) return [...APP_SERVICES];
  const list = only.split(',').map((s) => s.trim()).filter(Boolean);
  const bad = list.filter((s) => !APP_SERVICES.includes(s as AppService));
  if (bad.length) throw new Error(`Unknown service(s): ${bad.join(', ')} (expected ${APP_SERVICES.join(', ')})`);
  return list as AppService[];
}

/** Procfile (honcho/foreman/overmind compatible) — what `atrium start` runs. */
export function procfile(mode: 'dev' | 'prod'): string {
  const lines = APP_SERVICES.map((s) => `${s}: ${SERVICES[s].procfile[mode]}`);
  return `# Generated by \`atrium setup procfile\` (${mode}). \`atrium start\` runs the same commands;\n# any Procfile runner works too: honcho start · overmind start · foreman start\n${lines.join('\n')}\n`;
}

export function isBuilt(root: string, s: AppService): boolean {
  return existsSync(join(root, SERVICES[s].buildOutput));
}
